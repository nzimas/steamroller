"""Generate firmware/rhythm_fm/generated/poundhard_tables.h from Vascular's
PoundhardTables.h (read-only source checkout /Users/nzimas/development/vascular-ios).

Poundhard builds 128 carrier and 128 modulator single cycles of 1024 floats at
runtime (about 1 MB). The Rhythm has neither the RAM nor the flash, so this
keeps every fourth frame (0, 4, ..., 124) plus frame 127 -- 33 per set -- as
128-sample int16 cycles rendered from the same harmonic series, to be
interpolated between frames and samples on the device. The folder curves and
the decay / hold / sweep / transient laws are carried over unchanged.
"""
import hashlib
import math
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SOURCE = Path('/Users/nzimas/development/vascular-ios/Sources/CVascularOpcodes/src/PoundhardTables.h')
OUT = ROOT/'firmware/rhythm_fm/generated/poundhard_tables.h'
FRAMES = [min(4*i, 127) for i in range(33)]
LEN = 128


def array(text, name):
    m = re.search(r'%s\s*(\[[^=]*\])?\s*=\s*\{' % re.escape(name), text)
    if not m: raise ValueError(name)
    i = m.end()-1; depth = 0
    for j in range(i, len(text)):
        if text[j] == '{': depth += 1
        elif text[j] == '}':
            depth -= 1
            if depth == 0: return [float(x) for x in re.findall(r'-?\d+(?:\.\d*)?(?:e[+-]?\d+)?', text[i:j+1])]
    raise ValueError(name)


def cycles(series):
    out = []
    for f in FRAMES:
        row = series[f*80:(f+1)*80]
        cyc = []
        for i in range(LEN):
            ph = 2*math.pi*i/LEN
            y = 0.0
            for h in range(40):
                m, p = row[2*h], row[2*h+1]
                if m > 0: y += m*math.sin((h+1)*ph + p + math.pi/2)
            cyc.append(y)
        out.append(cyc)
    return out


def main():
    text = SOURCE.read_text()
    carrier = cycles(array(text, 'kCarrierWaves'))
    modulator = cycles(array(text, 'kModulatorWaves'))
    peak = max(abs(v) for set_ in (carrier, modulator) for c in set_ for v in c)
    scale = 32767/peak
    def ints(set_): return [[max(-32768, min(32767, round(v*scale))) for v in c] for c in set_]
    def c_rows(rows, per=16):
        lines = []
        for r in rows:
            chunks = [', '.join(str(v) for v in r[k:k+per]) for k in range(0, len(r), per)]
            lines.append('    {' + ',\n     '.join(chunks) + '}')
        return ',\n'.join(lines)
    def floats(vals): return ', '.join(repr(round(v, 6)) + 'f' if '.' in repr(round(v, 6)) or 'e' in repr(round(v, 6)) else repr(round(v, 6)) + '.0f' for v in vals)
    fold = array(text, 'kFoldCurve'); assert len(fold) == 17*65
    trans = array(text, 'kTransient'); assert len(trans) == 64*4
    parts = ['/* Generated by tools/gen_poundhard_tables.py from Vascular PoundhardTables.h',
             f' * (sha256 {hashlib.sha256(SOURCE.read_bytes()).hexdigest()}). Do not edit.',
             ' * Single cycles: frames ' + ', '.join(map(str, FRAMES[:4])) + ', ..., 124, 127 of the 128;',
             f' * {LEN} samples each, int16, value = wave * PH_WAVE_SCALE. */',
             '#pragma once', '#include <stdint.h>',
             f'#define PH_WAVE_FRAMES {len(FRAMES)}', f'#define PH_WAVE_LEN {LEN}',
             f'#define PH_WAVE_SCALE {1/scale!r}f',
             f'static const int16_t ph_carrier[{len(FRAMES)}][{LEN}] = {{\n{c_rows(ints(carrier))}\n}};',
             f'static const int16_t ph_modulator[{len(FRAMES)}][{LEN}] = {{\n{c_rows(ints(modulator))}\n}};',
             'static const float ph_fold_at[17] = {' + floats(array(text, 'kFoldAt')) + '};',
             'static const float ph_fold_curve[17][65] = {\n' + ',\n'.join('    {' + floats(fold[k*65:(k+1)*65]) + '}' for k in range(17)) + '\n};',
             'static const float ph_decay_at[18] = {' + floats(array(text, 'kDecayAt')) + '};',
             'static const float ph_decay_t60[18] = {' + floats(array(text, 'kDecayT60')) + '};',
             'static const float ph_hold_at[9] = {' + floats(array(text, 'kHoldAt')) + '};',
             'static const float ph_hold_seconds[9] = {' + floats(array(text, 'kHoldSeconds')) + '};',
             'static const float ph_sweep_at[9] = {' + floats(array(text, 'kSweepAt')) + '};',
             'static const float ph_sweep_tau[9] = {' + floats(array(text, 'kSweepTau')) + '};',
             'static const float ph_transient[64][4] = {\n' + ',\n'.join('    {' + floats(trans[k*4:(k+1)*4]) + '}' for k in range(64)) + '\n};', '']
    OUT.write_text('\n'.join(parts))
    print(OUT, OUT.stat().st_size, 'bytes source; wave scale', 1/scale)


if __name__ == '__main__': main()
