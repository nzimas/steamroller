"""Generate firmware/rhythm_fm/generated/bayarea_tables.h: the tables and
sample-rate constants of BAYAREA (firmware/rhythm_fm/bayarea.c) at 48 kHz.

BAYAREA comes from Tonitor (/Users/nzimas/development/mvave-fm1, read-only),
which runs at 44.1 kHz; its tables come from tools/gen_tables.py there. Here:
  EXP2_FRAC, TANH_Q15   as Tonitor's (rate-free);
  TAN_G, TANG_FMAX      tan(pi f / FS) up to 0.45 FS, at 48 kHz;
  BA_BW                 the 12 kHz Butterworth smoothing low-pass, at 48 kHz;
  BA_RES                the three resonators (508, 270, 1153 Hz): the same
                        pitch and ring time at 48 kHz, from Tonitor's 44.1 kHz
                        coefficients (checked by reproducing them).
The sine is SteamRoller's own (SINE[1025], fm6_reference_tables.h, Tonitor's
layout).
"""
import math
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / 'firmware/rhythm_fm/generated/bayarea_tables.h'
FS, TONITOR_FS = 48000, 44100
TONITOR_BW = [179736481, 359472962, 179736481, 87442742, 94632269]
TONITOR_RES = [(2141525796, -1073405498, 1229), (2145614805, -1073461545, 2048), (2118335556, -1073501581, 819)]


def arr(name, ctype, vals, per=12):
    out = [f'static const {ctype} {name}[{len(vals)}] = {{']
    for i in range(0, len(vals), per): out.append('    ' + ', '.join(str(v) for v in vals[i:i + per]) + ',')
    return out + ['};']


def butterworth(fc, fs):
    k = math.tan(math.pi * fc / fs); norm = 1 / (1 + math.sqrt(2) * k + k * k)
    b0 = k * k * norm
    return [round(x * (1 << 29)) for x in (b0, 2 * b0, b0, 2 * (k * k - 1) * norm, (1 - math.sqrt(2) * k + k * k) * norm)]


def main():
    if [abs(a - b) <= 2 for a, b in zip(butterworth(12000, TONITOR_FS), TONITOR_BW)] != [True] * 5:
        raise ValueError(f'12 kHz filter does not reproduce Tonitor: {butterworth(12000, TONITOR_FS)}')
    res = []
    for c1, c2, amp in TONITOR_RES:
        r = math.sqrt(-c2 / 2 ** 30)                       # pole radius per sample at 44.1 kHz
        w = math.acos(c1 / 2 ** 30 / (2 * r))              # pole angle per sample at 44.1 kHz
        hz = w * TONITOR_FS / (2 * math.pi)
        r48, w48 = r ** (TONITOR_FS / FS), 2 * math.pi * hz / FS   # the same ring time and pitch at 48 kHz
        res.append((round(2 * r48 * math.cos(w48) * 2 ** 30), round(-r48 * r48 * 2 ** 30), amp))
    fmax = int(0.45 * FS)
    lines = ['/* SPDX-License-Identifier: GPL-3.0-only', ' * Generated by tools/gen_bayarea_tables.py: BAYAREA at 48 kHz. Do not edit. */',
             '#pragma once', f'#define TANG_FMAX {fmax}']
    lines += arr('EXP2_FRAC', 'uint32_t', [int(round(65536 * 2 ** (i / 256))) for i in range(257)], 8)
    lines += arr('TANH_Q15', 'int16_t', [int(round(32767 * math.tanh(4 * i / 512))) for i in range(513)])
    lines += arr('TAN_G', 'uint32_t', [int(round((1 << 24) * math.tan(math.pi * (fmax * i / 512) / FS))) for i in range(513)], 8)
    lines += [f'static const int32_t BA_BW[5] = {{{", ".join(map(str, butterworth(12000, FS)))}}};   /* 12 kHz, Q29 */']
    lines += ['static const int32_t BA_RES[3][3] = {' + ', '.join('{%d, %d, %d}' % r for r in res) + '};   /* c1, c2 Q30; amp x 0.25 Q15 */']
    OUT.write_text('\n'.join(lines) + '\n')
    print(OUT, 'BW', butterworth(12000, FS), 'RES', res)


if __name__ == '__main__':
    main()
